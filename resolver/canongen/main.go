// Command canongen generates the Go projection of the resolver's CANONICAL evidence→state
// rule table. The single source of truth is the data file
// conformance/canonical/evidence_state_rules.json; this generator compiles it into
// engine/internal/resolver/ruletable_gen.go (var canonicalRuleTable), which the small
// hand-written evaluator in canonical.go walks. So the resolver's decision RULES live in
// exactly one place, as data, and the Go form is generated — not a hand-written twin
// (Phase 2 of the spec↔impl bridge). canonical_test.go proves the generated table + the
// evaluator equal the hand-coded ResolveObligation over the whole 64-class domain; the
// Lean model is proven equal to the same table in proofs/ForgeProofs/Canonical.lean.
//
// Regenerate:  go run ./internal/resolver/canongen   (from engine/)
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

type ruleSpec struct {
	Note  string            `json:"note"`
	Preds map[string]string `json:"predicates"`
	Rules []struct {
		Guard []string `json:"guard"`
		State string   `json:"state"`
	} `json:"rules"`
}

// leanState/goState map the canonical JSON state name to its Go flg constant.
var goState = map[string]string{
	"audit_only":   "flg.StateAuditOnly",
	"falsified":    "flg.StateFalsified",
	"reopened":     "flg.StateReopened",
	"contested":    "flg.StateContested",
	"discharged":   "flg.StateDischarged",
	"unverifiable": "flg.StateUnverifiable",
	"open":         "flg.StateOpen",
}

func main() {
	root := repoRoot()
	raw, err := os.ReadFile(filepath.Join(root, "conformance", "canonical", "evidence_state_rules.json"))
	must(err)
	var spec ruleSpec
	must(json.Unmarshal(raw, &spec))

	var b strings.Builder
	b.WriteString("// Code generated by internal/resolver/canongen from\n")
	b.WriteString("// conformance/canonical/evidence_state_rules.json; DO NOT EDIT.\n//\n")
	b.WriteString("// The resolver's evidence→state decision as DATA, generated from the single source of\n")
	b.WriteString("// truth. Priority-ordered — the first rule whose guard holds wins (see EvalCanonical).\n")
	b.WriteString("package resolver\n\n")
	b.WriteString(`import "github.com/websines/structor-harness/flg"` + "\n\n")
	b.WriteString("var canonicalRuleTable = []canonRule{\n")
	for _, r := range spec.Rules {
		st, ok := goState[r.State]
		if !ok {
			fmt.Fprintf(os.Stderr, "canongen: unknown state %q\n", r.State)
			os.Exit(1)
		}
		if len(r.Guard) == 0 {
			b.WriteString(fmt.Sprintf("\t{Guard: nil, State: %s},\n", st))
			continue
		}
		quoted := make([]string, len(r.Guard))
		for i, g := range r.Guard {
			quoted[i] = fmt.Sprintf("%q", g)
		}
		b.WriteString(fmt.Sprintf("\t{Guard: []string{%s}, State: %s},\n", strings.Join(quoted, ", "), st))
	}
	b.WriteString("}\n")

	out := filepath.Join(root, "resolver", "ruletable_gen.go")
	must(os.WriteFile(out, []byte(b.String()), 0o644))
	fmt.Printf("generated %s (%d canonical rules)\n", out, len(spec.Rules))
}

// repoRoot walks upward from the CWD to the workspace root — the directory holding
// conformance/canonical/evidence_state_rules.json. This makes the generator robust to the
// working directory, so it runs both as `go run ./internal/resolver/canongen` (from
// engine/) and via `go generate ./internal/resolver/` (CWD = the package dir).
func repoRoot() string {
	dir, _ := os.Getwd()
	for {
		if _, err := os.Stat(filepath.Join(dir, "conformance", "canonical", "evidence_state_rules.json")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			fmt.Fprintln(os.Stderr, "canongen: could not find the workspace root (conformance/canonical/) above the CWD")
			os.Exit(1)
		}
		dir = parent
	}
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
